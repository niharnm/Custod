import type { BurnoutCheckRecord, BrowserTab } from "@/lib/types";
import { cleanDomain, formatDate, statusLabel } from "@/lib/utils";

function tabLine(tab: BrowserTab): string {
  const label = tab.title || cleanDomain(tab.url) || tab.url || "Untitled tab";
  return tab.url ? `- [${label}](${tab.url})` : `- ${label}`;
}

export function checkToMarkdown(record: BurnoutCheckRecord): string {
  const analysis = record.analysis;
  const lines: string[] = [];

  lines.push(`# Custod burnout check`);
  lines.push("");
  lines.push(`Created: ${formatDate(record.createdAt)}`);
  lines.push(`Status: ${statusLabel(analysis.status)}`);
  lines.push(`Score: ${analysis.score}/100`);
  lines.push(`Main pattern: ${analysis.mainPattern}`);
  lines.push("");
  lines.push("## Pattern explanation");
  lines.push("");
  lines.push(analysis.patternExplanation);
  lines.push("");
  lines.push("## Risk breakdown");
  lines.push("");
  for (const risk of analysis.riskBreakdown) {
    lines.push(`- **${risk.label}** (${risk.level}, ${risk.score}): ${risk.explanation}`);
    for (const evidence of risk.evidence) lines.push(`  - ${evidence}`);
  }
  lines.push("");
  lines.push("## Reset plan");
  lines.push("");
  for (const step of analysis.resetPlan) {
    lines.push(`- **${step.title}** (${step.minutes} min): ${step.detail}`);
  }
  lines.push("");
  lines.push("## Evidence groups");
  lines.push("");
  for (const group of analysis.evidenceGroups) {
    lines.push(`### ${group.name}`);
    lines.push(group.explanation);
    lines.push("");
    for (const tab of group.tabs) lines.push(tabLine(tab));
    lines.push("");
  }
  lines.push("## Privacy");
  lines.push("");
  lines.push(analysis.privacySummary);
  lines.push("");
  lines.push("_Generated by Custod. Custod is not a medical diagnosis._");
  lines.push("");

  return lines.join("\n");
}
