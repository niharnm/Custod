import Foundation

// Port of lib/markdown.ts — the Markdown export the web app offers.

enum Markdown {
    static func checkToMarkdown(_ record: BurnoutCheckRecord) -> String {
        let analysis = record.analysis
        var lines: [String] = []

        let date = record.createdAt.formatted(date: .abbreviated, time: .shortened)

        lines.append("# Custod burnout check")
        lines.append("")
        lines.append("Created: \(date)")
        lines.append("Status: \(analysis.status.label)")
        lines.append("Score: \(analysis.score)/100")
        lines.append("Main pattern: \(analysis.mainPattern)")
        lines.append("")
        lines.append("## Pattern explanation")
        lines.append("")
        lines.append(analysis.patternExplanation)
        lines.append("")
        lines.append("## Risk breakdown")
        lines.append("")
        for risk in analysis.riskBreakdown {
            lines.append("- **\(risk.label)** (\(risk.level.rawValue), \(risk.score)): \(risk.explanation)")
            for evidence in risk.evidence { lines.append("  - \(evidence)") }
        }
        lines.append("")
        lines.append("## Reset plan")
        lines.append("")
        for step in analysis.resetPlan {
            lines.append("- **\(step.title)** (\(step.minutes) min): \(step.detail)")
        }
        lines.append("")
        lines.append("## Evidence groups")
        lines.append("")
        for group in analysis.evidenceGroups {
            lines.append("### \(group.name)")
            lines.append(group.explanation)
            lines.append("")
            for tab in group.tabs {
                let label = tab.title.isEmpty ? (tab.domain.isEmpty ? tab.url : tab.domain) : tab.title
                lines.append(tab.url.isEmpty ? "- \(label)" : "- [\(label)](\(tab.url))")
            }
            lines.append("")
        }
        lines.append("## Privacy")
        lines.append("")
        lines.append(analysis.privacySummary)
        lines.append("")
        lines.append("_Generated by Custod. Custod is not a medical diagnosis._")
        lines.append("")

        return lines.joined(separator: "\n")
    }
}
